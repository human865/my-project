f_справа = b**3 - b - 2

print(f"На левой границе {a} функция равна {f_слева}")
print(f"На правой границе {b} функция равна {f_справа}")

if f_слева * f_справа > 0:
    print("ошибка. На концах должны быть плюс и минус!")

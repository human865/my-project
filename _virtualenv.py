print("Мое уравнение: x^3 - x - 2 = 0")

левая_граница = input("Ввелите a [по умолчанию. 1]:")
a = float(левая_граница) if левая_граница else 1
правая_граница = input("Ввелите b [по умолчанию. 2]:")
b = float(правая_граница) if правая_граница else 2

точность = input("Ввелите ε [по умолчанию. 0.0001]:")
c = float(точность) if точность else 0.0001

